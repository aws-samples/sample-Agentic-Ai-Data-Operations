"""Prepare and validate the live demo MCP profile for all supported clients."""

from __future__ import annotations

import argparse
import json
import os
import shutil
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


ROOT = Path(__file__).resolve().parents[1]
PROFILE_PATH = ROOT / "mcp-profiles" / "demo" / "profile.json"
DEFAULT_CONFIG = ROOT / ".mcp.json"
OPTIONAL_CONFIG = ROOT / ".mcp.optional.json"

JSON_TARGETS = (
    Path(".mcp.json"),
    Path(".amazonq/mcp.json"),
    Path(".kiro/settings/mcp.json"),
    Path("plugins/claude-code/.mcp.json"),
    Path("adapters/claude-code/plugins/claude-code/.mcp.json"),
    Path("adapters/amazon-q/.amazonq/mcp.json"),
    Path("adapters/kiro/.kiro/settings/mcp.json"),
)
CODEX_TARGETS = (
    Path(".codex/config.toml"),
    Path("adapters/codex/.codex/config.toml"),
)


def load_json(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def load_profile() -> dict[str, Any]:
    profile = load_json(PROFILE_PATH)
    if profile.get("name") != "demo":
        raise ValueError("demo profile must have name=demo")
    return profile


def aws_server(region: str, aws_profile: str) -> dict[str, Any]:
    return {
        "command": "uvx",
        "args": [
            "mcp-proxy-for-aws==1.6.0",
            f"https://aws-mcp.{region}.api.aws/mcp",
            "--metadata",
            f"AWS_REGION={region}",
        ],
    }


def selected_servers(region: str, aws_profile: str) -> dict[str, Any]:
    profile = load_profile()
    optional = load_json(OPTIONAL_CONFIG)["mcpServers"]
    selected = {"aws-mcp": aws_server(region, aws_profile)}
    for name in profile["servers"]:
        if name == "aws-mcp":
            continue
        if name not in optional:
            raise ValueError(f"demo server {name!r} is missing from .mcp.optional.json")
        server = json.loads(json.dumps(optional[name]))
        env = server.setdefault("env", {})
        env["AWS_REGION"] = region
        env["AWS_PROFILE"] = aws_profile
        selected[name] = server
    return selected


def json_config(servers: dict[str, Any]) -> dict[str, Any]:
    return {"mcpServers": servers}


def toml_string(value: str) -> str:
    return json.dumps(value)


def toml_array(values: list[str]) -> str:
    return json.dumps(values)


def codex_config(servers: dict[str, Any], aws_profile: str) -> str:
    lines = [
        "# Generated by scripts/mcp_demo.py. Do not edit manually.",
        "# Restore the pre-demo profile with scripts/mcp_demo.py restore.",
        "",
        "[agents]",
        "",
        "[shell_environment_policy]",
        f"set = {{ AWS_PROFILE = {toml_string(aws_profile)} }}",
        "",
    ]
    for name, server in servers.items():
        lines.extend(
            [
                f'[mcp_servers."{name}"]',
                "enabled = true",
                f"command = {toml_string(server['command'])}",
                f"args = {toml_array(server.get('args', []))}",
            ]
        )
        env = server.get("env")
        if env:
            encoded = ", ".join(
                f"{toml_string(str(key))} = {toml_string(str(value))}"
                for key, value in env.items()
            )
            lines.append(f"env = {{ {encoded} }}")
        lines.append("")
    lines.extend(
        [
            "# Keep network access explicit; credentials come from the normal AWS chain.",
            "[sandbox_workspace_write]",
            "network_access = true",
            "",
        ]
    )
    return "\n".join(lines)


def target_contents(region: str, aws_profile: str) -> dict[Path, str]:
    servers = selected_servers(region, aws_profile)
    contents = {
        path: json.dumps(json_config(servers), indent=2) + "\n" for path in JSON_TARGETS
    }
    contents.update(
        {path: codex_config(servers, aws_profile) for path in CODEX_TARGETS}
    )
    return contents


def active_profile_mode() -> str:
    """Return ``"demo"`` when every client file is an exact demo activation, else ``"default"``.

    Validators use this so a profile produced by ``activate --apply`` is not
    reported as drift. Only an exact match counts: a partial activation or a
    hand-edited server list is still ``"default"`` and still fails validation.
    """
    try:
        canonical = load_json(DEFAULT_CONFIG).get("mcpServers", {})
        args = canonical.get("aws-mcp", {}).get("args", [])
        region = next(
            (a.split("=", 1)[1] for a in args if str(a).startswith("AWS_REGION=")), None
        )
        aws_profile = next(
            (
                server.get("env", {}).get("AWS_PROFILE")
                for name, server in canonical.items()
                if name != "aws-mcp" and server.get("env", {}).get("AWS_PROFILE")
            ),
            None,
        )
        if not region or not aws_profile:
            return "default"
        expected = target_contents(region, aws_profile)
    except (OSError, ValueError, KeyError, json.JSONDecodeError):
        return "default"
    for relative, content in expected.items():
        try:
            if (ROOT / relative).read_text(encoding="utf-8") != content:
                return "default"
        except OSError:
            return "default"
    return "demo"


def check_local_prerequisites(errors: list[str]) -> None:
    for executable in ("uv", "uvx"):
        if shutil.which(executable) is None:
            errors.append(f"missing executable: {executable}")
    if shutil.which("aws") is None:
        errors.append("missing executable: aws")


def check_aws_identity(region: str, aws_profile: str, errors: list[str]) -> None:
    if shutil.which("aws") is None:
        return
    env = os.environ.copy()
    env["AWS_PROFILE"] = aws_profile
    env["AWS_REGION"] = region
    env["AWS_DEFAULT_REGION"] = region
    result = subprocess.run(
        ["aws", "sts", "get-caller-identity", "--output", "json"],
        cwd=ROOT,
        env=env,
        capture_output=True,
        text=True,
        timeout=30,
        check=False,
    )
    if result.returncode:
        errors.append(
            "AWS identity check failed: "
            + (result.stderr.strip() or f"exit {result.returncode}")
        )
        return
    try:
        identity = json.loads(result.stdout)
    except json.JSONDecodeError:
        errors.append("AWS identity check returned invalid JSON")
        return
    print(
        "AWS identity: "
        f"{identity.get('Arn', 'unknown')} "
        f"(account {identity.get('Account', 'unknown')}, region {region})"
    )


def check_aws_capabilities(region: str, aws_profile: str, errors: list[str]) -> None:
    """Check the read-only AWS APIs needed before starting the live demo."""
    checks = (
        ("Glue Catalog", ["glue", "get-databases", "--max-results", "1"]),
        ("S3", ["s3api", "list-buckets"]),
        ("Lake Formation", ["lakeformation", "list-lf-tags", "--max-results", "1"]),
        ("IAM", ["iam", "list-roles", "--max-items", "1"]),
        ("CloudTrail", ["cloudtrail", "lookup-events", "--max-results", "1"]),
    )
    env = os.environ.copy()
    env["AWS_PROFILE"] = aws_profile
    env["AWS_REGION"] = region
    env["AWS_DEFAULT_REGION"] = region
    for label, arguments in checks:
        result = subprocess.run(
            ["aws", *arguments, "--output", "json"],
            cwd=ROOT,
            env=env,
            capture_output=True,
            text=True,
            timeout=45,
            check=False,
        )
        if result.returncode:
            detail = result.stderr.strip() or f"exit {result.returncode}"
            errors.append(f"{label} read-only check failed: {detail}")
        else:
            print(f"{label}: read-only access confirmed")


def check_profile(
    profile_name: str,
    region: str,
    aws_profile: str,
    offline: bool,
    skip_service_checks: bool,
) -> int:
    if profile_name != "demo":
        print(f"FAIL: unsupported profile {profile_name!r}; only demo is defined")
        return 1
    errors: list[str] = []
    profile = load_profile()
    if profile["region"] != region:
        print(f"Using region override: {region}")
    if profile["aws_profile"] != aws_profile:
        print(f"Using AWS profile override: {aws_profile}")
    check_local_prerequisites(errors)
    try:
        servers = selected_servers(region, aws_profile)
        print("Demo servers: " + ", ".join(servers))
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        errors.append(f"cannot build demo server set: {exc}")
    if not offline:
        check_aws_identity(region, aws_profile, errors)
        if not skip_service_checks and not errors:
            check_aws_capabilities(region, aws_profile, errors)
    if errors:
        print(f"FAIL: {len(errors)} demo readiness issue(s)")
        for error in errors:
            print(f"  - {error}")
        return 1
    print("PASS: demo MCP profile is locally ready")
    if offline:
        print("AWS identity check skipped (--offline)")
    return 0


def activate(region: str, aws_profile: str) -> int:
    contents = target_contents(region, aws_profile)
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    backup_root = ROOT / ".mcp-backups" / "demo" / stamp
    for relative, content in contents.items():
        target = ROOT / relative
        if not target.is_file():
            raise FileNotFoundError(f"cannot back up missing target: {relative}")
        backup = backup_root / relative
        backup.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(target, backup)
        target.write_text(content, encoding="utf-8")
    print(f"Activated demo MCP profile for {len(contents)} client files.")
    print(f"Backup: {backup_root.relative_to(ROOT)}")
    print("Restart the active Claude Code, Codex, Amazon Q, or Kiro session.")
    return 0


def restore(backup: str) -> int:
    backup_root = (ROOT / backup).resolve()
    if not backup_root.is_dir() or ROOT not in backup_root.parents:
        print("FAIL: backup must be a directory inside the repository")
        return 1
    restored = 0
    for relative in (*JSON_TARGETS, *CODEX_TARGETS):
        source = backup_root / relative
        target = ROOT / relative
        if source.is_file():
            shutil.copy2(source, target)
            restored += 1
    if restored != len(JSON_TARGETS) + len(CODEX_TARGETS):
        print(f"FAIL: backup is incomplete; restored {restored} files")
        return 1
    print(f"Restored {restored} MCP client files from {backup_root.relative_to(ROOT)}.")
    print("Restart the active client to reload the restored profile.")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    check_parser = subparsers.add_parser("check", help="validate demo readiness")
    check_parser.add_argument("--profile", default="demo")
    check_parser.add_argument("--region", default=load_profile()["region"])
    check_parser.add_argument("--aws-profile", default=load_profile()["aws_profile"])
    check_parser.add_argument("--offline", action="store_true")
    check_parser.add_argument("--skip-service-checks", action="store_true")

    activate_parser = subparsers.add_parser("activate", help="activate demo configs")
    activate_parser.add_argument("--profile", default="demo")
    activate_parser.add_argument("--region", default=load_profile()["region"])
    activate_parser.add_argument("--aws-profile", default=load_profile()["aws_profile"])
    activate_parser.add_argument("--apply", action="store_true", required=True)

    restore_parser = subparsers.add_parser("restore", help="restore a demo backup")
    restore_parser.add_argument("--backup", required=True)

    args = parser.parse_args()
    if args.command == "check":
        return check_profile(
            args.profile,
            args.region,
            args.aws_profile,
            args.offline,
            args.skip_service_checks,
        )
    if args.command == "activate":
        if args.profile != "demo":
            print(f"FAIL: unsupported profile {args.profile!r}")
            return 1
        return activate(args.region, args.aws_profile)
    return restore(args.backup)


if __name__ == "__main__":
    raise SystemExit(main())
